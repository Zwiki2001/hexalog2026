let currentLang = 'en';

function setLanguage(lang) {
  if (!TRANSLATIONS[lang]) return;
  currentLang = lang;
  document.documentElement.lang = lang;
  // RTL support for Arabic
  document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = TRANSLATIONS[lang][key];
    if (text !== undefined) el.textContent = text;
  });
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  // Persist language choice
  try { localStorage.setItem('hl_lang', lang); } catch(e) {}
}

function t(key) {
  return TRANSLATIONS[currentLang]?.[key] || TRANSLATIONS['en'][key] || key;
}

// Auto-restore last selected language
document.addEventListener('DOMContentLoaded', () => {
  // Wire lang buttons (works for pages that don't have inline onclick)
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => setLanguage(btn.dataset.lang));
  });
  let saved = 'en';
  try { saved = localStorage.getItem('hl_lang') || 'en'; } catch(e) {}
  setLanguage(TRANSLATIONS[saved] ? saved : 'en');
});
